#!/usr/bin/env python3
# vcxproj -> CMake donusturucu (Client tarafi)
# Srcs/Client/*.vcxproj dosyalarini okuyup Srcs/Client/CMakeLists.txt uretir.
import re, glob, os

ROOT = os.path.dirname(os.path.abspath(__file__))
CLIENT = os.path.abspath(os.path.join(ROOT, '..', '..', 'Srcs', 'Client'))
OUT = os.path.join(CLIENT, 'CMakeLists.txt')

RELEASE_RE = re.compile(
    r"<ItemDefinitionGroup Condition=\"[^\"]*Release\|Win32'\">(.*?)</ItemDefinitionGroup>",
    re.S)

def tag(blk, name):
    m = re.findall(rf'<{name}>(.*?)</{name}>', blk, re.S)
    return m[0].strip() if m else ''

def plist(s):
    return [x.strip() for x in s.replace('\n', ';').split(';')
            if x.strip() and not x.strip().startswith('%(')]

def cmake_path(p):
    p = p.replace('\\', '/')
    return p

projects = []
for fn in sorted(glob.glob(os.path.join(CLIENT, '*.vcxproj'))):
    s = open(fn, encoding='utf-8', errors='replace').read()
    name = os.path.splitext(os.path.basename(fn))[0]
    kind = tag(s, 'ConfigurationType') or 'StaticLibrary'

    # Release bloku
    m = RELEASE_RE.search(s)
    blk = m.group(1) if m else ''

    defines = plist(tag(blk, 'PreprocessorDefinitions'))
    defines = [d for d in defines if d not in ('NDEBUG', '_LIB')]
    defines.append('NDEBUG')

    includes = plist(tag(blk, 'AdditionalIncludeDirectories'))
    includes = [os.path.relpath(os.path.join(CLIENT, i), CLIENT).replace('\\', '/')
                if not i.startswith('$') else i for i in includes]

    deps = plist(tag(blk, 'AdditionalDependencies'))
    libdirs = plist(tag(blk, 'AdditionalLibraryDirectories'))
    libdirs = [os.path.relpath(os.path.join(CLIENT, d), CLIENT).replace('\\', '/')
               if not d.startswith('$') else d for d in libdirs]

    pch = tag(blk, 'PrecompiledHeaderFile') or None
    pch_use = '<PrecompiledHeader>Use</PrecompiledHeader>' in blk or '<PrecompiledHeader>Use</PrecompiledHeader>' in s
    subsys = tag(blk, 'SubSystem')
    addopts = tag(blk, 'AdditionalOptions')
    ignorelibs = re.findall(r'<IgnoreSpecificDefaultLibraries>(.*?)</IgnoreSpecificDefaultLibraries>', blk, re.S)
    ignorelibs = [x for x in plist(';'.join(ignorelibs))]

    sources = re.findall(r'<ClCompile Include="([^"]+)"', s)
    sources = [cmake_path(x) for x in sources]
    if sources:
        if not pch and pch_use:
            # vcxproj PCH=Use ama header adi bos: proje dizininde stdafx.h ara
            pdir = os.path.dirname(sources[0])
            for cand in ('stdafx.h', 'StdAfx.h'):
                if os.path.exists(os.path.join(CLIENT, pdir, cand)):
                    pch = cand
                    break
        if pch:
            pch = f"{os.path.dirname(sources[0])}/{pch}"
    rcs = [cmake_path(x) for x in re.findall(r'<ResourceCompile Include="([^"]+)"', s)]
    refs = [os.path.splitext(os.path.basename(r))[0]
            for r in re.findall(r'<ProjectReference Include="([^"]+)"', s)]

    projects.append(dict(name=name, kind=kind, defines=defines, includes=includes,
                         deps=deps, libdirs=libdirs, pch=pch, subsys=subsys,
                         addopts=addopts, ignorelibs=ignorelibs, sources=sources,
                         rcs=rcs, refs=refs))

w = []
w.append('# AUTO-GENERATED by tools/script/cmake_client_gen.py - vcxproj uzerinden uretildi')
w.append('# elle duzenleme; degisiklik icin uretici scripti kullan')
w.append('cmake_minimum_required(VERSION 3.15)')
w.append('project(Client LANGUAGES C CXX RC)')
w.append('set(CMAKE_C_STANDARD 17)')
w.append('set(CMAKE_CXX_STANDARD 20)')
w.append('set(CMAKE_CXX_EXTENSIONS OFF)')
w.append('set(CMAKE_MSVC_RUNTIME_LIBRARY "MultiThreaded$<$<CONFIG:Debug>:Debug>")')
w.append('set(EXTERN_INCLUDE_DIR "${CMAKE_CURRENT_SOURCE_DIR}/../Extern/include")')
w.append('set(EXTERN_LIB_DIR "${CMAKE_CURRENT_SOURCE_DIR}/../Extern/lib")')
w.append('set(CMAKE_ARCHIVE_OUTPUT_DIRECTORY "${CMAKE_BINARY_DIR}/lib")')
w.append('set(CMAKE_RUNTIME_OUTPUT_DIRECTORY "${CMAKE_BINARY_DIR}/bin")')
w.append('add_library(client_base INTERFACE)')
w.append('target_compile_options(client_base INTERFACE')
w.append('    /MP /W3 /Oi /Gy')
w.append('    /wd4996 /wd5054 /wd5055 /wd4244 /wd4242 /wd4267 /wd4838 /wd4805')
w.append('    /wd4146 /wd4018 /wd4309 /wd4804 /wd4101 /wd4065 /wd4477 /wd4005 /wd4834)')
w.append('target_compile_definitions(client_base INTERFACE')
w.append('    WIN32 NOMINMAX _CRT_SECURE_NO_WARNINGS _WINSOCK_DEPRECATED_NO_WARNINGS')
w.append('    _SILENCE_ALL_CXX17_DEPRECATION_WARNINGS _SILENCE_ALL_CXX20_DEPRECATION_WARNINGS)')
w.append('target_include_directories(client_base INTERFACE "${EXTERN_INCLUDE_DIR}")')
w.append('')

for p in projects:
    n = p['name']
    if p['kind'] == 'Application':
        continue
    w.append(f"# ==== {n} ====")
    srcs = ' '.join(f'"{s}"' for s in p['sources'])
    w.append(f"add_library({n} STATIC {srcs})")
    w.append(f"target_link_libraries({n} PUBLIC client_base)")
    if p['pch']:
        w.append(f"target_precompile_headers({n} PRIVATE \"{p['pch']}\")")
    if p['defines']:
        w.append(f"target_compile_definitions({n} PRIVATE {' '.join(p['defines'])})")
    if p['includes']:
        w.append(f"target_include_directories({n} PRIVATE {' '.join(p['includes'])})")
    w.append('')

for p in projects:
    if p['kind'] != 'Application':
        continue
    n = p['name']
    w.append(f"# ==== {n} (uygulama) ====")
    srcs = ' '.join(f'"{s}"' for s in (p['sources'] + p['rcs']))
    w.append(f"add_executable({n} WIN32 {srcs})")
    w.append(f"target_link_libraries({n} PUBLIC client_base)")
    if p['pch']:
        w.append(f"target_precompile_headers({n} PRIVATE \"{p['pch']}\")")
    if p['defines']:
        w.append(f"target_compile_definitions({n} PRIVATE {' '.join(p['defines'])})")
    if p['includes']:
        w.append(f"target_include_directories({n} PRIVATE {' '.join(p['includes'])})")
    if p['refs']:
        w.append(f"target_link_libraries({n} PRIVATE {' '.join(p['refs'])})")
    ld = ['"${EXTERN_LIB_DIR}"' if d == '../Extern/lib' else f'"{d}"' for d in p['libdirs']]
    if ld:
        w.append(f"target_link_directories({n} PRIVATE {' '.join(ld)})")
    if p['deps']:
        w.append(f"target_link_libraries({n} PRIVATE {' '.join(p['deps'])})")
    if p['ignorelibs']:
        w.append(f"target_link_options({n} PRIVATE {' '.join('/NODEFAULTLIB:'+x for x in p['ignorelibs'])})")
    if '4099' in p['addopts']:
        w.append(f"target_link_options({n} PRIVATE /ignore:4099)")
    w.append(f"set_target_properties({n} PROPERTIES OUTPUT_NAME metin2client)")
    w.append('')

open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(w) + '\n')
print(f"[OK] {OUT} uretildi ({len(projects)} proje)")
